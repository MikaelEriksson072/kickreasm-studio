/* include/c64-hardware.asm: every known symbol as `.label NAME = $xxxx // description` */
import type { Settings } from '../types';
import { SYM } from '../c64/symbols';
import { h4 } from '../util/hex';

interface IncludeSym { name: string; addr: number; desc: string }

export function hardwareInclude(S: Pick<Settings, 'hexCase'>): string {
  const out = ['// C64 hardware, KERNAL and system symbols', '// generated by Mimir Studio for Kick Assembler 5.x', ''];
  const cats = new Map<string, IncludeSym[]>();
  for (const s of SYM.exact.values()) { if (/\+/.test(s.name)) continue; if (!cats.has(s.cat)) cats.set(s.cat, []); cats.get(s.cat)!.push(s); }
  for (const r of SYM.regions) { if (!cats.has(r.cat)) cats.set(r.cat, []); cats.get(r.cat)!.push({ name: r.name, addr: r.start, desc: r.desc }); }
  for (const [cat, list] of cats) {
    out.push(`// ---- ${cat} ----`);
    for (const s of list.sort((x, y) => x.addr - y.addr)) {
      const left = `.label ${s.name.padEnd(18)} = $${S.hexCase === 'upper' ? h4(s.addr).toUpperCase() : h4(s.addr)}`;
      out.push(`${left.padEnd(36)}// ${s.desc}`);
    }
    out.push('');
  }
  return out.join('\n');
}
