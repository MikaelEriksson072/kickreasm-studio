/* Files of an exported Kick Assembler project besides the generated sources (spec 11.4). */
import type { BuildScript, Project, RenderResult, Settings, VerifyResult, Vfs } from './types';
import { h4 } from './util/hex';
import { makePrg } from './c64/prg';
import { serializeProject } from './project';
import { NOTES_TEXT_FILE, notesExport, notesFor } from './notes-doc';
import { patchEnd, patchFileName, patchPrg, unpatchedFiles } from './patch';

export function buildScripts(S: Settings, names: string[]): { 'build.bat': string; 'build.sh': string } {
  const bat = ['@echo off', 'rem Build script generated by Mimir Studio', `set JAVA=${S.javaPath}`, `set KICKASS=${S.kickJar}`, `set VICE=${S.vicePath}`, '']
    .concat(names.map(n => `"%JAVA%" -jar "%KICKASS%" ${n}.asm -odir ${S.outDir} ${S.kickArgs} || exit /b 1`))
    .concat([`start "" "%VICE%" ${S.viceArgs} -moncommands ${S.outDir}\\${names[0]}.vs -autostart ${S.outDir}\\${names[0]}.prg`, '']).join('\r\n');
  const sh = ['#!/bin/sh', '# Build script generated by Mimir Studio', 'set -e', `JAVA="\${JAVA:-${S.javaPath}}"`, 'KICKASS="${KICKASS:-$HOME/c64/KickAss.jar}"', 'VICE="${VICE:-x64sc}"', '']
    .concat(names.map(n => `"$JAVA" -jar "$KICKASS" ${n}.asm -odir ${S.outDir} ${S.kickArgs}`))
    .concat([`"$VICE" ${S.viceArgs} -moncommands ${S.outDir}/${names[0]}.vs -autostart ${S.outDir}/${names[0]}.prg`, '']).join('\n');
  return { 'build.bat': bat, 'build.sh': sh };
}

/** `notes`: the notes document the export writes (NOTES.html or NOTES.txt: the project has bookmarks or comments) */
export function readme(project: Pick<Project, 'name' | 'files'> & Partial<Pick<Project, 'patches'>>, R: RenderResult, notes: string | null = null): string {
  const names = R.fileNames, patches = project.patches ?? [], on = patches.filter(p => !p.off).length;
  return [`# ${project.name} — Kick Assembler project`, '', 'Generated by Mimir Studio from:', '',
    ...project.files.map(f => `- \`${f.name}\` loaded at $${h4(f.load)} (${f.bytes.length} bytes)`),
    ...(on ? ['', `with ${on === 1 ? 'a patch' : `${on} patches`} written over them: the sources and \`out/\` have ${on === 1 ? 'it' : 'them'} in, \`original/\` has the files as they were loaded.`] : []),
    '', '## Layout', '',
    ...names.map(n => `- \`${n}.asm\` — re-assembled source`),
    // not written when the source uses the raw addresses (hwInclude 'none')
    ...(R.files['include/c64-hardware.asm'] != null ? ['- `include/c64-hardware.asm` — VIC-II, SID, CIA, KERNAL and system symbols'] : []),
    ...Object.keys(R.files).filter(f => f.startsWith('data/')).map(f => `- \`${f}\` — a block saved as a binary file, loaded with \`.import binary\``),
    ...Object.keys(R.files).filter(k => typeof R.files[k] !== 'string' && !k.startsWith('data/')).map(k => `- \`${k}\` — binary data referenced from the source`),
    ...(notes ? [`- \`${notes}\` — your bookmarks and comments, each with the code around it${notes === NOTES_TEXT_FILE ? ', as plain text' : ' (open it in a browser)'}`] : []),
    ...patches.map(p => `- \`patches/${patchFileName(p.name)}\` — the patch "${p.name}" as a PRG: $${h4(p.start)}-$${h4(patchEnd(p) - 1)} (${p.bytes.length} bytes), loaded where it goes${p.off ? ' (switched off: not in the sources)' : ''}`),
    '- `original/` — the input PRG files', '- `out/` — the verified re-assembled PRG files', '', '## Build', '',
    'Windows: `build.bat` · macOS/Linux: `sh build.sh` (set KICKASS to your KickAss.jar).', '',
    'Every exported source was re-assembled and compared byte for byte with the original before export.', ''].join('\n');
}

export const BUILD_SCRIPTS: readonly BuildScript[] = ['build.bat', 'build.sh'];

/** the build scripts the export writes: the user's edited ones (Project.scripts), else the generated ones */
export function projectScripts(project: Partial<Pick<Project, 'scripts'>>, S: Settings, names: string[]): Record<BuildScript, string> {
  const out = buildScripts(S, names);
  for (const k of BUILD_SCRIPTS) { const t = project.scripts?.[k]; if (typeof t === 'string') out[k] = t; }
  return out;
}

/** Generated sources plus build scripts and README: everything the source view shows. */
export function projectTextFiles(project: Project, R: RenderResult, S: Settings): Vfs {
  return { ...projectScripts(project, S, R.fileNames), 'README.md': readme(project, R, notesFor(project, R, S)) };
}

/** The complete exported project folder: sources, binaries, scripts, project file, the notes document, inputs and
 *  verified outputs. `generated`: the export time shown in the notes document (Settings.notesFormat). */
export function exportFiles(project: Project, R: RenderResult, S: Settings, verified?: VerifyResult | null, generated?: Date): Vfs {
  const out: Vfs = { ...R.files, ...projectTextFiles(project, R, S) };
  const notes = notesExport(project, R, S, generated);
  if (notes) out[notes[0]] = notes[1];
  out[`${project.name}.mimir.json`] = JSON.stringify(serializeProject(project), null, 1);
  // the input files as they were loaded; each patch as a PRG of its own
  for (const f of unpatchedFiles(project.files, project.patches ?? [])) out[`original/${f.name}`] = makePrg(f.load, f.bytes);
  for (const p of project.patches ?? []) out[`patches/${patchFileName(p.name)}`] = patchPrg(p);
  if (verified && verified.ok) for (const r of verified.results) if (r.prg) out[`${S.outDir}/${r.path.replace(/\.asm$/, '.prg')}`] = r.prg;
  return out;
}
