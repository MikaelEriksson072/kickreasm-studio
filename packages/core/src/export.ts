/* Files of an exported Kick Assembler project besides the generated sources (spec 11.4). */
import type { BuildScript, Cartridge, FileInput, Project, RenderResult, Settings, VerifyResult, Vfs } from './types';
import { h4 } from './util/hex';
import { makePrg } from './c64/prg';
import { cartridgeSource, chipFromPrg, crtBase, crtOutputName, crtSourceName, describeCrt, parseCrt, rebuildCrt, type Crt } from './c64/crt';
import { serializeProject } from './project';
import { NOTES_TEXT_FILE, notesExport, notesFor } from './notes-doc';
import { patchEnd, patchFileName, patchSource, unpatchedFiles } from './patch';

/** A project's cartridge (spec 13.9): its source, which builds the image, and the image's name; null without one */
export interface CartBuild { entry: string; output: string }
export const cartBuild = (project: Partial<Pick<Project, 'cart'>>): CartBuild | null => {
  if (!project.cart) return null;
  const base = crtBase(project.cart);
  return { entry: crtSourceName(base), output: crtOutputName(base) };
};

/** `cart`: the sources build a cartridge, whose own source comes last and which VICE then starts (-cartcrt) */
export function buildScripts(S: Settings, names: string[], cart: CartBuild | null = null): { 'build.bat': string; 'build.sh': string } {
  const entries = [...names.map(n => `${n}.asm`), ...(cart ? [cart.entry] : [])];
  const run = (sep: string) => (cart ? `-cartcrt ${S.outDir}${sep}${cart.output}` : `-autostart ${S.outDir}${sep}${names[0]}.prg`);
  const bat = ['@echo off', 'rem Build script generated by Mimir Studio', `set JAVA=${S.javaPath}`, `set KICKASS=${S.kickJar}`, `set VICE=${S.vicePath}`, '']
    .concat(entries.map(e => `"%JAVA%" -jar "%KICKASS%" ${e} -odir ${S.outDir} ${S.kickArgs} || exit /b 1`))
    .concat([`start "" "%VICE%" ${S.viceArgs} -moncommands ${S.outDir}\\${names[0]}.vs ${run('\\')}`, '']).join('\r\n');
  const sh = ['#!/bin/sh', '# Build script generated by Mimir Studio', 'set -e', `JAVA="\${JAVA:-${S.javaPath}}"`, 'KICKASS="${KICKASS:-$HOME/c64/KickAss.jar}"', 'VICE="${VICE:-x64sc}"', '']
    .concat(entries.map(e => `"$JAVA" -jar "$KICKASS" ${e} -odir ${S.outDir} ${S.kickArgs}`))
    .concat([`"$VICE" ${S.viceArgs} -moncommands ${S.outDir}/${names[0]}.vs ${run('/')}`, '']).join('\n');
  return { 'build.bat': bat, 'build.sh': sh };
}

/** the project's cartridge image read, or null (none, or one that cannot be read) */
const projectCrt = (project: Partial<Pick<Project, 'cart'>>): Crt | null => {
  try { return project.cart ? parseCrt(project.cart.crt, project.cart.name) : null; } catch { return null; }
};

/**
 * The cartridge's own source (`<name>.crt.asm`) and the binaries of the chips the project does not re-assemble
 * (`banks/<chip>.bin`); null without a cartridge. A chip is re-assembled by the first file that is it, whole.
 */
export function cartridgeFiles(project: { files: readonly FileInput[]; cart?: Cartridge | null }, R: Pick<RenderResult, 'fileNames'>, S: Pick<Settings, 'outDir' | 'hexCase'>): (CartBuild & { files: Vfs }) | null {
  const crt = projectCrt(project), build = cartBuild(project);
  if (!crt || !build || !project.cart) return null;
  const sources = new Map<number, string>();
  project.files.forEach((f, i) => { const c = f.chip != null ? crt.chips[f.chip] : undefined; if (c && f.bytes.length === c.data.length && !sources.has(c.index) && R.fileNames[i]) sources.set(c.index, R.fileNames[i]); });
  const { source, files } = cartridgeSource(project.cart.name, crt, { outDir: S.outDir, sources, hexCase: S.hexCase });
  return { ...build, files: { [build.entry]: source, ...files } };
}

/** The image the project's chips make: the one opened, with what the project wrote over its chips (patches) */
export function expectedCartridge(project: { files: readonly FileInput[]; cart?: Cartridge | null }): Uint8Array | null {
  return builtCartridge(project, project.files.map(f => makePrg(f.load, f.bytes)))?.crt ?? null;
}

/**
 * The cartridge image rebuilt from the PRGs the sources built (one per project file, in order; null where none was
 * built): what `<name>.crt.asm` writes. `problems`: chips whose PRG does not fit the chip.
 */
export function builtCartridge(project: { files: readonly FileInput[]; cart?: Cartridge | null }, prgs: readonly (Uint8Array | null | undefined)[]): { name: string; crt: Uint8Array; problems: string[] } | null {
  const crt = projectCrt(project), build = cartBuild(project);
  if (!crt || !build) return null;
  const built = new Map<number, Uint8Array>(), problems: string[] = [];
  project.files.forEach((f, i) => {
    const c = f.chip != null ? crt.chips[f.chip] : undefined;
    if (!c || f.bytes.length !== c.data.length || built.has(c.index)) return;
    const bytes = chipFromPrg(crt, c, prgs[i] ?? null);
    if (bytes) built.set(c.index, bytes); else problems.push(`${f.name}: no PRG built at the chip's address`);
  });
  const r = rebuildCrt(crt, built);
  return { name: build.output, crt: r.crt, problems: [...problems, ...r.problems] };
}

/** `notes`: the notes document the export writes (NOTES.html or NOTES.txt: the project has bookmarks or comments) */
export function readme(project: Pick<Project, 'name' | 'files'> & Partial<Pick<Project, 'patches' | 'cart'>>, R: RenderResult, notes: string | null = null): string {
  const names = R.fileNames, patches = project.patches ?? [], on = patches.filter(p => !p.off).length;
  const crt = projectCrt(project), cart = cartBuild(project);
  const chips = project.files.filter(f => f.chip != null).length;
  return [`# ${project.name} — Kick Assembler project`, '', 'Generated by Mimir Studio from:', '',
    ...(crt && project.cart ? [`- the cartridge \`${project.cart.name}\`: ${describeCrt(crt)}${crt.name ? `, "${crt.name}"` : ''}, ${crt.chips.length} chip${crt.chips.length === 1 ? '' : 's'}; ${chips === 1 ? 'this chip is' : `these ${chips} chips are`} re-assembled:`] : []),
    ...project.files.map(f => `- \`${f.name}\` loaded at $${h4(f.load)} (${f.bytes.length} bytes)`),
    ...(on ? ['', `with ${on === 1 ? 'a patch' : `${on} patches`} written over them: the sources and \`out/\` have ${on === 1 ? 'it' : 'them'} in, \`original/\` has the files as they were loaded.`] : []),
    '', '## Layout', '',
    ...names.map(n => `- \`${n}.asm\` — re-assembled source`),
    ...(cart && crt ? [`- \`${cart.entry}\` — the cartridge: writes \`${cart.output}\` (its header and CHIP packets, the re-assembled chips from their PRGs${crt.chips.length > chips ? ', the others from `banks/`' : ''}); build it after the sources`] : []),
    ...(cart && crt && crt.chips.length > chips ? ['- `banks/` — the chips that are not re-assembled, as they are in the cartridge'] : []),
    // not written when the source uses the raw addresses (hwInclude 'none')
    ...(R.files['include/c64-hardware.asm'] != null ? ['- `include/c64-hardware.asm` — VIC-II, SID, CIA, KERNAL and system symbols'] : []),
    ...Object.keys(R.files).filter(f => f.startsWith('data/')).map(f => `- \`${f}\` — a block saved as a binary file, loaded with \`.import binary\``),
    ...Object.keys(R.files).filter(k => typeof R.files[k] !== 'string' && !k.startsWith('data/')).map(k => `- \`${k}\` — binary data referenced from the source`),
    ...(notes ? [`- \`${notes}\` — your bookmarks and comments, each with the code around it${notes === NOTES_TEXT_FILE ? ', as plain text' : ' (open it in a browser)'}`] : []),
    ...patches.map(p => `- \`patches/${patchFileName(p.name, 'asm')}\` — the patch "${p.name}", $${h4(p.start)}-$${h4(patchEnd(p) - 1)} (${p.bytes.length} bytes), as a source of its own: it assembles to a PRG that loads where it goes${p.off ? ' (switched off: not in the sources)' : ''}`),
    `- \`original/\` — the input PRG files${cart ? ' and the cartridge' : ''}`, `- \`out/\` — the verified re-assembled PRG files${cart ? ` and \`${cart.output}\`` : ''}`, '', '## Build', '',
    'Windows: `build.bat` · macOS/Linux: `sh build.sh` (set KICKASS to your KickAss.jar).', '',
    'Every exported source was re-assembled and compared byte for byte with the original before export.', ''].join('\n');
}

export const BUILD_SCRIPTS: readonly BuildScript[] = ['build.bat', 'build.sh'];

/** the build scripts the export writes: the user's edited ones (Project.scripts), else the generated ones */
export function projectScripts(project: Partial<Pick<Project, 'scripts' | 'cart'>>, S: Settings, names: string[]): Record<BuildScript, string> {
  const out = buildScripts(S, names, cartBuild(project));
  for (const k of BUILD_SCRIPTS) { const t = project.scripts?.[k]; if (typeof t === 'string') out[k] = t; }
  return out;
}

/** Generated sources plus build scripts and README (and a cartridge's source): everything the source view shows. */
export function projectTextFiles(project: Project, R: RenderResult, S: Settings): Vfs {
  const cart = cartridgeFiles(project, R, S);
  return { ...(cart ? { [cart.entry]: cart.files[cart.entry] } : {}), ...projectScripts(project, S, R.fileNames), 'README.md': readme(project, R, notesFor(project, R, S)) };
}

/** The complete exported project folder: sources, binaries, scripts, project file, the notes document, inputs and
 *  verified outputs. `generated`: the export time shown in the notes document (Settings.notesFormat). */
export function exportFiles(project: Project, R: RenderResult, S: Settings, verified?: VerifyResult | null, generated?: Date): Vfs {
  const out: Vfs = { ...R.files, ...cartridgeFiles(project, R, S)?.files, ...projectTextFiles(project, R, S) };
  const notes = notesExport(project, R, S, generated);
  if (notes) out[notes[0]] = notes[1];
  out[`${project.name}.mimir.json`] = JSON.stringify(serializeProject(project), null, 1);
  // the input files as they were loaded; each patch as a Kick Assembler source of its own
  for (const f of unpatchedFiles(project.files, project.patches ?? [])) out[`original/${f.name}`] = makePrg(f.load, f.bytes);
  if (project.cart) out[`original/${project.cart.name}`] = project.cart.crt;
  for (const p of project.patches ?? []) {
    const from = project.files.find(f => p.start >= f.load && patchEnd(p) <= f.load + f.bytes.length)?.name;
    out[`patches/${patchFileName(p.name, 'asm')}`] = patchSource(R, S, p, from);
  }
  if (verified && verified.ok) for (const r of verified.results) if (r.prg) out[`${S.outDir}/${r.path.replace(/\.asm$/, '.prg')}`] = r.prg;
  const crt = verified && verified.ok ? builtCartridge(project, verified.results.map(r => r.prg)) : null;
  if (crt && !crt.problems.length) out[`${S.outDir}/${crt.name}`] = crt.crt;
  return out;
}
