/* Stand-ins for the C64 ROMs, for when no ROM files are found. The KERNAL holds the small pieces packers run
 * through (the interrupt entries, the jump table's indirect jumps); everything else is a JAM, and the unpacker
 * traps the routines it knows (CHROUT, GETIN, clear screen, BASIC RUN, ...) before the CPU gets there.
 * initStandIn() sets up RAM and I/O as a C64 has them after it starts. */
import type { C64, Roms } from './c64.ts';

/** the RAM vectors $0314-$0333 as RESTOR sets them */
export const KERNAL_VECTORS = [
  0xea31, 0xfe66, 0xfe47, 0xf34a, 0xf291, 0xf20e, 0xf250, 0xf333, 0xf157, 0xf1ca, 0xf6ed, 0xf13e, 0xf32f, 0xfe66, 0xf4a5, 0xf5ed,
];
/** the BASIC vectors $0300-$030b */
export const BASIC_VECTORS = [0xe38b, 0xa483, 0xa57c, 0xa71a, 0xa7e4, 0xae86];

/** BASIC's CHRGET routine, which it copies to $0073 */
const CHRGET = [0xe6, 0x7a, 0xd0, 0x02, 0xe6, 0x7b, 0xad, 0x00, 0x08, 0xc9, 0x3a, 0xb0, 0x0a, 0xc9, 0x20, 0xf0, 0xef, 0x38, 0xe9, 0x30, 0x38, 0xe9, 0xd0, 0x60];

/** the jump table entries that jump through a RAM vector: entry -> vector */
export const VECTORED: Record<number, number> = {
  0xffc0: 0x031a, 0xffc3: 0x031c, 0xffc6: 0x031e, 0xffc9: 0x0320, 0xffcc: 0x0322, 0xffcf: 0x0324,
  0xffd2: 0x0326, 0xffe1: 0x0328, 0xffe4: 0x032a, 0xffe7: 0x032c,
};

export function standInRoms(): Roms {
  const kernal = new Uint8Array(0x2000).fill(0x02);
  const basic = new Uint8Array(0x2000).fill(0x02);
  const put = (rom: Uint8Array, base: number, addr: number, bytes: number[]) => rom.set(bytes, addr - base);
  const k = (addr: number, bytes: number[]) => put(kernal, 0xe000, addr, bytes);
  // IRQ/BRK entry: save the registers, then JMP ($0316) for BRK or JMP ($0314)
  k(0xff48, [0x48, 0x8a, 0x48, 0x98, 0x48, 0xba, 0xbd, 0x04, 0x01, 0x29, 0x10, 0xf0, 0x03, 0x6c, 0x16, 0x03, 0x6c, 0x14, 0x03]);
  // the KERNAL's IRQ handler (the unpacker updates the clock and keyboard first): ack CIA 1, restore, RTI
  k(0xea31, [0xad, 0x0d, 0xdc, 0x4c, 0x81, 0xea]);
  k(0xea7e, [0xad, 0x0d, 0xdc]);
  k(0xea81, [0x68, 0xa8, 0x68, 0xaa, 0x68, 0x40]);
  // NMI: SEI, JMP ($0318); the default handler acks CIA 2 and returns
  k(0xfe43, [0x78, 0x6c, 0x18, 0x03]);
  k(0xfe47, [0x48, 0x8a, 0x48, 0x98, 0x48, 0xad, 0x0d, 0xdd, 0x4c, 0xbc, 0xfe]);
  k(0xfebc, [0x68, 0xa8, 0x68, 0xaa, 0x68, 0x40]);
  // the jump table's vectored entries, LOAD and SAVE
  for (const [entry, vector] of Object.entries(VECTORED)) k(Number(entry), [0x6c, vector & 0xff, vector >> 8]);
  k(0xffd5, [0x4c, 0x9e, 0xf4]);
  k(0xf49e, [0x86, 0xc3, 0x84, 0xc4, 0x6c, 0x30, 0x03]);
  k(0xffd8, [0x4c, 0xdd, 0xf5]);
  k(0xf5dd, [0x6c, 0x32, 0x03]);
  // NMI, reset and IRQ vectors
  k(0xfffa, [0x43, 0xfe, 0xe2, 0xfc, 0x48, 0xff]);
  return { kernal, basic, chargen: new Uint8Array(0x1000), source: 'stand-ins (no ROM files)' };
}

/** RAM, colour RAM and I/O as the KERNAL and BASIC leave them after power-on, at the READY prompt. */
export function initStandIn(m: C64): void {
  const ram = m.ram;
  ram.fill(0);
  const w = (a: number, v: number) => { ram[a] = v & 0xff; ram[a + 1] = v >> 8; };
  m.ddr = 0x2f; m.port = 0x37; m.updateMap();
  ram[0] = 0x2f; ram[1] = 0x37;
  w(0x03, 0xb1aa); w(0x05, 0xb391);
  ram[0x16] = 0x19;
  w(0x2b, 0x0801); w(0x2d, 0x0803); w(0x2f, 0x0803); w(0x31, 0x0803); w(0x33, 0xa000); w(0x37, 0xa000);
  ram[0x53] = 0x03; ram[0x54] = 0x4c;
  ram.set(CHRGET, 0x73);
  ram.set([0x80, 0x4f, 0xc7, 0x52, 0x58], 0x8b);
  ram[0x9a] = 3; ram[0x9d] = 0x80;
  w(0xb2, 0x033c);
  ram[0xc5] = ram[0xcb] = 0x40;
  w(0xd1, 0x0400); ram[0xd5] = 39;
  for (let line = 0; line < 25; line++) ram[0xd9 + line] = 0x80 | ((0x0400 + line * 40) >> 8);
  w(0xf3, 0xd800); w(0xf5, 0xeb81);
  w(0x0281, 0x0800); w(0x0283, 0xa000);
  ram[0x0286] = 0x0e; ram[0x0287] = 0x06; ram[0x0288] = 0x04; ram[0x0289] = 0x0a; ram[0x028b] = 0x04;
  w(0x028f, 0xeb48); ram[0x02a6] = 1;
  BASIC_VECTORS.forEach((v, i) => w(0x0300 + 2 * i, v));
  ram[0x0310] = 0x4c; w(0x0311, 0xb248);
  KERNAL_VECTORS.forEach((v, i) => w(0x0314 + 2 * i, v));
  ram.fill(0x20, 0x0400, 0x07e8);
  m.color.fill(0x0e);
  // VIC: text mode, screen at $0400, light blue on blue
  const vic = m.vic.regs;
  vic.fill(0);
  vic[0x11] = 0x1b; vic[0x16] = 0xc8; vic[0x18] = 0x15; vic[0x20] = 0x0e; vic[0x21] = 0x06;
  vic[0x22] = 0x01; vic[0x23] = 0x02; vic[0x24] = 0x03;
  m.vic.compare = 0;
  // CIA 1: keyboard columns out, the KERNAL's 1/60 s timer A interrupt running
  const c1 = m.cia1;
  c1.ddra = 0xff; c1.pra = 0x7f; c1.ddrb = 0; c1.prb = 0xff;
  c1.tal = c1.ta = 0x4025; c1.cra = 0x01; c1.mask = 0x01;
  // CIA 2: VIC bank 0, serial lines released
  const c2 = m.cia2;
  c2.ddra = 0x3f; c2.pra = 0x07; c2.ddrb = 0; c2.prb = 0xff;
}
